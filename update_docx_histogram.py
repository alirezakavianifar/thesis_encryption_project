def replace_in_paragraph(paragraph, mapping):
    text = paragraph.text
    new = text
    for old, val in mapping.items():
        if old in new:
            new = new.replace(old, val)
    if new != text:
        if paragraph.runs:
            paragraph.runs[0].text = new
            for run in paragraph.runs[1:]:
                run.text = ""
        else:
            paragraph.text = new
        return True
    return False


def main():
    doc = Document(DOCX)
    n = 0
    all_maps = [ENTROPY_ENC, NPCR_UACI, TIMING, CORR, CORR_RED, dict(TEXT)]

    for para in doc.paragraphs:
        for m in all_maps:
            if replace_in_paragraph(para, m):
                n += 1
                break

    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for para in cell.paragraphs:
                    for m in all_maps:
                        if replace_in_paragraph(para, m):
                            n += 1
                            break

    out_path = OUT
    try:
        doc.save(out_path)
    except PermissionError:
        out_path = DOCX.with_name("main_updated_histogram.docx")
        doc.save(out_path)
    print(f"Updated {out_path.name}: {n} replacements")


if __name__ == "__main__":
    main()
